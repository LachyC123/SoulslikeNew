export function textWidth(text: string, big = false): number {
  const cw = big ? 6 : 4;
  return text.length * cw - 1;
}

/** Draw text with a 1px dark outline; (x, y) is the top-left. */
export function drawText(g: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, big = false, outline = '#140e14'): void {
  const font = big ? BIG : SMALL;
  const cw = big ? 6 : 4;
  x = Math.round(x);
  y = Math.round(y);
  for (const pass of [0, 1]) {
    g.fillStyle = pass === 0 ? outline : color;
    let cx = x;
    for (const ch of text) {
      const glyph = font[ch];
      if (glyph) {
        for (let gy = 0; gy < glyph.length; gy++)
          for (let gx = 0; gx < glyph[gy].length; gx++) {
            if (glyph[gy][gx] !== '1') continue;
            if (pass === 0) g.fillRect(cx + gx - 1, y + gy - 1, 3, 3);
            else g.fillRect(cx + gx, y + gy, 1, 1);
          }
      }
      cx += cw;
    }
  }
}
